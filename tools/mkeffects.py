#!/usr/bin/env python3
"""Set up the battle effect programs as overlays.

Battle effects (Radical Dreamers Edition dev names `prog/<name>.prg`) load at
0x801C5E00. Each file is one word of effect id, then code, then data and zero
padding to the end of its last sector. The list is effects/effects.tsv: one row
per distinct program (several disc file numbers can name the same bytes; the
lowest is used). Six programs exist only on Disc 2; they go to iso/files/d2/.

usage:
  tools/mkeffects.py extract <disc1.bin> [<disc2.bin>]   # copy them into iso/files/
  tools/mkeffects.py gen                                 # write effects/*.yaml + effects.mk
then `make split-ov_eff_<name>` (or tools/mkeffects.py split) and `make`.
"""
import csv, hashlib, os, struct, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import extract_files  # noqa: E402

VRAM = 0x801C5E00
TSV = ROOT / "effects" / "effects.tsv"

TEMPLATE = """name: OV_EFF_{BASE}
# Battle effect program {base}.prg (dev name from the Radical Dreamers Edition), disc file
# {where}. Loaded into the effect slot at 0x801C5E00; the first word is the effect id
# ({hdr:#x}).{alias} Generated by tools/mkeffects.py.
sha1: {sha1}
options:
  basename: ov_eff_{base}
  target_path: iso/files/{file}.bin
  elf_path: build/ov_eff_{base}.elf
  base_path: ..
  platform: psx
  compiler: PSYQ

  asm_path: asm/ov_eff_{base}
  src_path: src/ov_eff_{base}
  build_path: build

  ld_script_path: linker_scripts/ov_eff_{base}.ld
  ld_dependencies: True
  ld_align_segment_vram_end: False
  ld_align_section_vram_end: False
  rodata_string_guesser_level: 2
  data_string_guesser_level: 2

  find_file_boundaries: True
  gp_value: 0x8006CE1C

  o_as_suffix: True
  use_legacy_include_asm: False

  section_order: {order}

  # Main-EXE symbols, so calls into main get the same names.
  symbol_addrs_path:
    - symbol_addrs.txt

  undefined_funcs_auto_path: linker_scripts/ov_eff_{base}_undefined_funcs_auto.txt
  undefined_syms_auto_path: linker_scripts/ov_eff_{base}_undefined_syms_auto.txt

  subalign: 2

  string_encoding: ASCII
  data_string_encoding: ASCII

segments:
  - name: ov_eff_{base}
    type: code
    start: 0x0
    vram: 0x801C5E00
    subsegments:
{subs}
  - [{size:#x}]
"""


def programs():
    with open(TSV, newline="") as fh:
        return [r for r in csv.DictReader(fh, delimiter="\t")]


def rel(p):
    """iso/files path stem of a program: NNNN, or d2/NNNN for Disc-2-only ones."""
    return ("d2/" if p["disc"] == "2" else "") + "%04d" % int(p["file"])


def extract(disc1, disc2=None):
    for disc, path in (("1", disc1), ("2", disc2)):
        todo = [p for p in programs() if p["disc"] == disc]
        if not todo:
            continue
        if path is None:
            print(f"no Disc 2 image given: skipping {len(todo)} Disc-2-only programs")
            continue
        with open(path, "rb") as f:
            ents = extract_files.load_table(f)
            for p in todo:
                lba, n = extract_files.span(ents, int(p["file"]))
                out = ROOT / "iso" / "files" / f"{rel(p)}.bin"
                out.parent.mkdir(parents=True, exist_ok=True)
                out.write_bytes(extract_files.read_sectors(f, lba, n))
        print(f"Disc {disc}: extracted {len(todo)} programs")


def layout(b):
    """(end of code, does the tail hold pointers into the code, i.e. jump tables)."""
    ws = struct.unpack_from(f"<{len(b) // 4}I", b)
    jr = [i for i, w in enumerate(ws) if w == 0x03E00008]  # jr $ra
    code_end = (jr[-1] + 2) * 4
    jt = any(VRAM + 4 <= w < VRAM + code_end for w in ws[code_end // 4:])
    return code_end, jt


def gen():
    names, defs = [], []
    for p in programs():
        base = p["name"]
        b = (ROOT / "iso" / "files" / f"{rel(p)}.bin").read_bytes()
        code_end, jt = layout(b)
        c = f"{base}_801C5E04"
        if jt:  # the tail has jump tables: make it the C file's .rodata so their labels resolve
            order = '[".data", ".text", ".rodata", ".bss"]'
            subs = [f"      - [0x0, data, data_801C5E00]  # effect id",
                    f"      - [0x4, c, {c}]",
                    f"      - [{code_end:#x}, .rodata, {c}]"]
        else:
            order = '[".rodata", ".text", ".data", ".bss"]'
            subs = [f"      - [0x0, rodata, rodata_801C5E00]  # effect id",
                    f"      - [0x4, c, {c}]",
                    f"      - [{code_end:#x}, data, data_{VRAM + code_end:08X}]"]
        where = f"#{p['file']}" + (" on Disc 2 only" if p["disc"] == "2" else "")
        also = [a for a in p["also"].split(",") if a]
        alias = f"\n# The same bytes are also files {', '.join('#' + a for a in also)}." if also else ""
        (ROOT / "effects" / f"ov_eff_{base}.yaml").write_text(TEMPLATE.format(
            BASE=base.upper(), base=base, where=where, hdr=struct.unpack_from("<I", b)[0],
            alias=alias, sha1=hashlib.sha1(b).hexdigest(), file=rel(p), order=order,
            subs="\n".join(subs), size=len(b)))
        names.append(f"ov_eff_{base}")
        defs.append(f"ov_eff_{base}_FILE := {rel(p)}")
    mk = ["# Battle effect programs. Generated by tools/mkeffects.py from effects/effects.tsv.",
          "# Disc-2-only programs are extracted from Disc 2 into iso/files/d2/.",
          "EFFECTS := " + " \\\n           ".join(names), "", *defs, "",
          "$(foreach e,$(EFFECTS),$(eval $(e)_YAML := effects/$(e).yaml))", ""]
    (ROOT / "effects" / "effects.mk").write_text("\n".join(mk))
    print(f"wrote {len(names)} configs")


def split():
    for p in programs():
        ov = f"ov_eff_{p['name']}"
        r = subprocess.run([sys.executable, "-m", "splat", "split", f"effects/{ov}.yaml"],
                           cwd=ROOT, capture_output=True, text=True)
        print(ov, "ok" if r.returncode == 0 else "FAILED\n" + r.stdout[-2000:] + r.stderr[-2000:])


if __name__ == "__main__":
    if len(sys.argv) >= 3 and sys.argv[1] == "extract":
        extract(*sys.argv[2:4])
    elif sys.argv[1:] == ["gen"]:
        gen()
    elif sys.argv[1:] == ["split"]:
        split()
    else:
        sys.exit(__doc__)
